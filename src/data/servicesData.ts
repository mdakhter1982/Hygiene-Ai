export function buildWhatsAppLink(serviceName?: string, customMessage?: string): string {
  let text = '';
  if (customMessage) {
    text = customMessage;
  } else if (serviceName) {
    text = `Hi HCS Cleaning Services, I am interested in ${serviceName} in Kolkata. Please share the price and available service slots.`;
  } else {
    text = 'Hi HCS Cleaning Services, I want to enquire about cleaning services in Kolkata. Please share details and pricing.';
  }
  return `https://wa.me/${BUSINESS_INFO.whatsappRaw}?text=${encodeURIComponent(text)}`;
}

